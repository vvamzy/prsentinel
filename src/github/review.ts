import type { Config } from '../config.js';
import { renderCommentBody } from '../review/prompts.js';
import { encodeMarker } from '../state.js';
import {
  compareFindings,
  type Finding,
  type ReviewPayload,
  type ReviewPlan,
} from '../review/types.js';

/**
 * Builds the final `pulls.createReview` payload.
 *
 * Two things live in the body that are easy to get wrong:
 *  - File summaries go inside <details> so the walkthrough stays scannable.
 *  - The last-reviewed marker is an HTML comment, invisible in the rendered
 *    markdown but retrievable on the next run for incremental review.
 */

export function buildReviewBody(
  plan: ReviewPlan,
  config: Config,
  opts: { headSha: string; skipped: Array<{ file: string; reason: string }> },
): string {
  const parts: string[] = [];

  parts.push('## 📋 Walkthrough');
  parts.push('');
  parts.push(plan.walkthrough || '_No walkthrough was generated._');

  if (plan.fileSummaries.length > 0) {
    parts.push('');
    parts.push('<details>');
    parts.push(`<summary><b>Changed files (${plan.fileSummaries.length})</b></summary>`);
    parts.push('');
    const sorted = [...plan.fileSummaries].sort((a, b) => (a.file < b.file ? -1 : 1));
    for (const s of sorted) {
      parts.push(`- \`${s.file}\` — ${s.summary}`);
    }
    parts.push('');
    parts.push('</details>');
  }

  if (opts.skipped.length > 0) {
    const files = opts.skipped.map((s) => `\`${s.file}\``).join(', ');
    parts.push('');
    parts.push(`<sub>Skipped (not reviewed): ${files}</sub>`);
  }

  const counts = countBySeverity(plan.findings);
  if (Object.keys(counts).length > 0) {
    parts.push('');
    const summary = (['critical', 'major', 'minor', 'info'] as const)
      .filter((k) => counts[k])
      .map((k) => `${counts[k]} ${k}`)
      .join(', ');
    parts.push(`<sub>Findings: ${summary}</sub>`);
  }

  parts.push('');
  parts.push('<sub>🤖 Generated by <b>prsentinel</b> — open-source AI review, running in your Actions pipeline</sub>');
  parts.push('');
  parts.push(encodeMarker(opts.headSha));

  return parts.join('\n');
}

export function countBySeverity(findings: Finding[]): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const f of findings) counts[f.severity] = (counts[f.severity] ?? 0) + 1;
  return counts;
}

/**
 * Convert findings into inline review comments.
 *
 * Order is deterministic (severity, then file, then line) so re-running on
 * the same diff produces byte-identical output — which is what makes the
 * fixture tests meaningful.
 */
export function buildReviewComments(plan: ReviewPlan, config: Config): ReviewPayload['comments'] {
  const sorted = [...plan.findings].sort(compareFindings);
  const comments: ReviewPayload['comments'] = [];

  for (const f of sorted) {
    if (f.suggestion !== undefined && f.suggestion.trim() === '') continue;
    const body = renderCommentBody(config, f);
    if (f.startLine !== undefined && f.startLine < f.line) {
      comments.push({
        path: f.file,
        line: f.line,
        side: 'RIGHT',
        start_line: f.startLine,
        start_side: 'RIGHT',
        body,
      });
    } else {
      comments.push({
        path: f.file,
        line: f.line,
        side: 'RIGHT',
        body,
      });
    }
  }
  return comments;
}

/** Assemble the complete payload ready for the API. */
export function buildReviewPayload(
  plan: ReviewPlan,
  config: Config,
  opts: {
    headSha: string;
    skipped: Array<{ file: string; reason: string }>;
  },
): ReviewPayload {
  const comments = buildReviewComments(plan, config);
  const body = buildReviewBody(plan, config, opts);

  const hasCritical = plan.findings.some((f) => f.severity === 'critical');
  const event =
    config.reviews.request_changes_on_critical && hasCritical ? 'REQUEST_CHANGES' : 'COMMENT';

  return { event, commit_id: opts.headSha, body, comments };
}

/**
 * Render a dry-run payload to disk-friendly JSON. Kept separate from the
 * API path so tests can snapshot exactly what would be posted.
 */
export function serializePayload(payload: ReviewPayload): string {
  return JSON.stringify(payload, null, 2);
}
